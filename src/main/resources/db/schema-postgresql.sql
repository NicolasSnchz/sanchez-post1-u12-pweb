-- Esquema de produccion (PostgreSQL) de la entidad Pedido. Idempotente: se ejecuta en cada arranque
-- con el perfil prod y solo crea la tabla la primera vez. Hibernate (ddl-auto=validate) comprueba despues
-- que coincida con la entidad.
CREATE TABLE IF NOT EXISTS pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_email   VARCHAR(255),
    tipo_cliente    VARCHAR(255),
    subtotal        DOUBLE PRECISION,
    descuento       DOUBLE PRECISION,
    iva             DOUBLE PRECISION,
    total           DOUBLE PRECISION,
    estado          VARCHAR(255),
    notas_internas  VARCHAR(255),
    fecha_creacion  TIMESTAMP(6)
);
